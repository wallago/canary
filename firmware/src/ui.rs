//! The screen: the UI generated from `assets/ui.slint`, the platform Slint
//! runs on, and the bridge from its software renderer to the panel.
//!
//! Slint owns the layout now — nothing here draws a border, places a label or
//! wipes a box. This module only answers two questions Slint asks of a bare
//! board: what time is it, and where do rendered pixels go.

use alloc::{boxed::Box, rc::Rc};
use core::{ops::Range, time::Duration};

use canary_core::prelude::*;
use embedded_graphics::{
    draw_target::DrawTarget,
    pixelcolor::{Rgb565, raw::RawU16},
    prelude::{Point, Size},
    primitives::Rectangle,
};
use esp_hal::time::Instant;
use slint::{
    PhysicalSize, PlatformError,
    platform::{
        Platform, WindowAdapter,
        software_renderer::{
            LineBufferProvider, MinimalSoftwareWindow, RepaintBufferType, Rgb565Pixel,
        },
    },
};

use crate::display;

/// Rust side of `assets/ui.slint`, generated by `build.rs`.
// Generated code: the workspace's doc and pedantic lints aren't ours to
// satisfy there, and regenerating it on every build makes fixing them futile.
#[allow(
    missing_debug_implementations,
    missing_docs,
    unreachable_pub,
    unused_qualifications,
    clippy::pedantic,
    clippy::missing_docs_in_private_items,
    clippy::expect_used,
    clippy::panic,
    clippy::unwrap_used
)]
pub(crate) mod generated {
    slint::include_modules!();
}

/// Slint's view of this board: one fixed window and the boot clock.
struct Panel {
    /// The only window; Slint asks for it once, when the UI is created.
    window: Rc<MinimalSoftwareWindow>,
}

impl Platform for Panel {
    fn create_window_adapter(&self) -> core::result::Result<Rc<dyn WindowAdapter>, PlatformError> {
        Ok(self.window.clone())
    }

    fn duration_since_start(&self) -> Duration {
        // `Instant`'s epoch is boot, which is exactly the zero Slint wants for
        // timers and animations.
        Duration::from_micros(Instant::now().duration_since_epoch().as_micros())
    }
}

/// Lends Slint one panel row at a time, then pushes the rendered span out.
struct LineSink<'a, D>
where
    D: DrawTarget<Color = Rgb565>,
{
    /// One full panel row; Slint renders into the dirty span of it.
    buffer: &'a mut [Rgb565Pixel],
    /// Where the rendered span goes.
    display: &'a mut D,
    /// First error the panel returned. `process_line` cannot report one, so it
    /// is parked here for [`render`] to pick up.
    failed: &'a mut Option<D::Error>,
}

impl<D> LineBufferProvider for LineSink<'_, D>
where
    D: DrawTarget<Color = Rgb565>,
{
    type TargetPixel = Rgb565Pixel;

    fn process_line(
        &mut self,
        line: usize,
        range: Range<usize>,
        render_fn: impl FnOnce(&mut [Self::TargetPixel]),
    ) {
        let pixels = &mut self.buffer[range.clone()];
        render_fn(pixels);

        // Keep rendering after a failure — Slint's own bookkeeping expects
        // every line it asked for to come back — but stop touching the bus.
        if self.failed.is_some() || range.is_empty() {
            return;
        }

        let (Ok(x), Ok(y), Ok(width)) = (
            i32::try_from(range.start),
            i32::try_from(line),
            u32::try_from(range.len()),
        ) else {
            return;
        };

        // Same 565 bit layout on both sides; the driver handles byte order.
        let colors = pixels.iter().map(|p| Rgb565::from(RawU16::new(p.0)));

        // One row per call: the driver sets the window once, then streams.
        if let Err(e) = self.display.fill_contiguous(
            &Rectangle::new(Point::new(x, y), Size::new(width, 1)),
            colors,
        ) {
            *self.failed = Some(e);
        }
    }
}

/// Hand Slint the window it draws into, and start its clock.
///
/// # Errors
///
/// [`Error::Init`] if a platform has already been installed.
pub(crate) fn init() -> Result<Rc<MinimalSoftwareWindow>> {
    // `ReusedBuffer`: the panel's own RAM holds the last frame, so Slint
    // repaints only the lines that actually changed. On an unbuffered panel
    // that is the difference between a visible flicker and none.
    let window = MinimalSoftwareWindow::new(RepaintBufferType::ReusedBuffer);
    window.set_size(PhysicalSize::new(
        u32::from(display::WIDTH),
        u32::from(display::HEIGHT),
    ));

    slint::platform::set_platform(Box::new(Panel {
        window: Rc::clone(&window),
    }))
    .map_err(|_| Error::Init("slint platform"))?;

    Ok(window)
}

/// Draw whatever changed since the last call, straight to the panel.
///
/// `buffer` is one full panel row, reused across frames.
///
/// # Errors
///
/// Propagates the first error the panel returned.
pub(crate) fn render<D>(
    window: &MinimalSoftwareWindow,
    display: &mut D,
    buffer: &mut [Rgb565Pixel],
) -> core::result::Result<(), D::Error>
where
    D: DrawTarget<Color = Rgb565>,
{
    let mut failed = None;

    window.draw_if_needed(|renderer| {
        renderer.render_by_line(LineSink {
            buffer,
            display,
            failed: &mut failed,
        });
    });

    failed.map_or(Ok(()), Err)
}
