/// Assemble and initialise the panel from an already-wired QSPI bus and I2C bus.
pub fn build<'d>(
    bus: SpiDmaBus<'d, Blocking>,
    i2c: I2c<'d, Blocking>,
    delay: &mut Delay,
) -> DriverResult<PanelDisplay<'d>, QspiInterface<'d>, TcaReset<'d>> {
    let interface = QspiInterface {
        bus,
        pixel_started: false,
    };
    let reset = TcaReset {
        i2c,
        delay: Delay::new(),
    };

    St77916::builder(interface, reset, DisplaySize::new(360, 360))
        .with_init_commands(PANEL_INIT)
        .unbuffered::<Rgb565>()
        .build(ColorMode::Rgb565, delay)
}

